"""Generates FABRICATED (dummy) catchment data for 100 synthetic locations,
covering the socio-demographic / competitive-landscape / accessibility
attribute list requested by the user. This is NOT real INS/OSM data and
must never be merged into `data/location_features/*.json` (the real,
one-off-pulled feature cache for the project's 6 actual stores) - it
exists purely to demonstrate scale/distribution choices at n=100 for a
hypothetical larger catchment-clustering exercise.

Every attribute is drawn conditional on a per-location `urbanicity` class
(urban_core / suburban / rural), so the synthetic dataset has the kind of
internal correlation structure real catchment data would have (e.g. dense
urban catchments also skew younger, wealthier, more transit-served) rather
than 25 independent, uncorrelated columns.

Output: `data/location_features/synthetic/synthetic_catchment_100.csv`
Reasoning doc (scale + distribution + parameters + rationale per
attribute): `docs/location_similarity/synthetic_catchment_dummy_data.md`
(generated by `attribute_reasoning_doc()` in this same script).

Reproduce with: `PYTHONPATH=src python3 scripts/generate_synthetic_catchment_dummy_data.py`
"""

import numpy as np
import pandas as pd

from shopping_missions.config import RANDOM_STATE

N = 100
OUT_CSV = "data/location_features/synthetic/synthetic_catchment_100.csv"
OUT_DOC = "docs/location_similarity/synthetic_catchment_dummy_data.md"

Z10, Z90 = -1.2815515655446004, 1.2815515655446004  # standard normal 10th/90th pctile


def beta_mean_conc(rng, mean, kappa, size):
    """Beta(mean*kappa, (1-mean)*kappa) - the mean/concentration
    parameterization: var = mean(1-mean)/(kappa+1), always valid for any
    kappa > 0, unlike specifying (a, b) or (mean, sd) directly."""
    return rng.beta(mean * kappa, (1 - mean) * kappa, size=size)


def neg_binomial_mean_disp(rng, mean, dispersion_factor, size):
    """Negative binomial parameterized by (mean, dispersion_factor) where
    variance = mean * dispersion_factor (dispersion_factor > 1 means
    overdispersed relative to Poisson, where variance = mean).
    r = mean / (dispersion_factor - 1); p = r / (r + mean)."""
    mean = np.asarray(mean, dtype=float)
    r = mean / (dispersion_factor - 1)
    p = r / (r + mean)
    return rng.negative_binomial(r, p, size=size)


def by_class(urbanicity, urban_core, suburban, rural):
    """Maps a per-row urbanicity label to a per-row parameter value."""
    lut = {"urban_core": urban_core, "suburban": suburban, "rural": rural}
    return np.array([lut[u] for u in urbanicity])


def generate(n: int = N, random_state: int = RANDOM_STATE) -> pd.DataFrame:
    rng = np.random.default_rng(random_state)
    rows: dict[str, np.ndarray] = {}

    rows["location_id"] = np.arange(1, n + 1)

    # --- urbanicity: drawn first, everything else conditions on it ---
    urbanicity = rng.choice(
        ["urban_core", "suburban", "rural"], size=n, p=[0.30, 0.35, 0.35]
    )
    rows["urbanicity"] = urbanicity

    # === 1. Socio-demographic ===================================
    dens_median = by_class(urbanicity, 6000, 1200, 150)
    rows["population_density_km2"] = rng.lognormal(np.log(dens_median), 0.45)

    pop_median = by_class(urbanicity, 350_000, 60_000, 15_000)
    rows["population_size"] = rng.lognormal(np.log(pop_median), 0.85)

    growth_mean = by_class(urbanicity, 0.8, 0.3, -0.9)
    growth_sd = by_class(urbanicity, 1.2, 1.0, 1.3)
    rows["population_growth_pct_yr"] = rng.normal(growth_mean, growth_sd)

    rows["working_age_pct"] = 100 * beta_mean_conc(rng, 0.66, 55, n)
    elderly_mean = by_class(urbanicity, 0.15, 0.18, 0.23)
    rows["elderly_pct"] = 100 * beta_mean_conc(rng, elderly_mean, 45, n)
    kids_mean = by_class(urbanicity, 0.30, 0.32, 0.24)
    rows["families_with_kids_pct"] = 100 * beta_mean_conc(rng, kids_mean, 35, n)

    income_median_val = by_class(urbanicity, 5200, 4400, 3200)
    rows["household_income_median_ron"] = rng.lognormal(np.log(income_median_val), 0.25)
    income_dispersion_sigma = rng.gamma(shape=4.0, scale=0.05, size=n)  # within-catchment inequality
    rows["household_income_p10_ron"] = rows["household_income_median_ron"] * np.exp(income_dispersion_sigma * Z10)
    rows["household_income_p90_ron"] = rows["household_income_median_ron"] * np.exp(income_dispersion_sigma * Z90)

    hh_size_mean = by_class(urbanicity, 2.3, 2.6, 2.9)
    rows["household_size_avg"] = np.clip(rng.normal(hh_size_mean, 0.3), 1.2, 5.0)
    single_mean = by_class(urbanicity, 0.32, 0.22, 0.15)
    rows["pct_single_person_households"] = 100 * beta_mean_conc(rng, single_mean, 40, n)

    edu_props = {
        "urban_core": [0.15, 0.45, 0.40],
        "suburban": [0.25, 0.50, 0.25],
        "rural": [0.40, 0.48, 0.12],
    }
    edu = np.array([rng.dirichlet(np.array(edu_props[u]) * 40) for u in urbanicity])
    rows["pct_education_primary"] = 100 * edu[:, 0]
    rows["pct_education_secondary"] = 100 * edu[:, 1]
    rows["pct_education_tertiary"] = 100 * edu[:, 2]

    employ_mean = by_class(urbanicity, 0.66, 0.63, 0.58)
    rows["employment_rate_pct"] = 100 * beta_mean_conc(rng, employ_mean, 60, n)

    occ_props = {
        "urban_core": [0.55, 0.30, 0.15],
        "suburban": [0.40, 0.45, 0.15],
        "rural": [0.15, 0.55, 0.30],
    }
    occ = np.array([rng.dirichlet(np.array(occ_props[u]) * 30) for u in urbanicity])
    rows["pct_white_collar_of_employed"] = 100 * occ[:, 0]
    rows["pct_blue_collar_of_employed"] = 100 * occ[:, 1]
    rows["pct_other_of_employed"] = 100 * occ[:, 2]

    # === 2. Competitive & retail landscape =======================
    pop_scale = (rows["population_size"] / 100_000) ** 0.6
    tier_base_rate = {"hyper": 0.3, "super": 1.2, "discount": 2.5, "convenience": 4.0}
    total_competitors = np.zeros(n)
    for tier, base_rate in tier_base_rate.items():
        mean_count = np.maximum(base_rate * pop_scale, 0.05)
        counts = neg_binomial_mean_disp(rng, mean_count, dispersion_factor=1.8, size=n)
        rows[f"competitors_{tier}_count"] = counts
        total_competitors += counts
    rows["competitors_total_count"] = total_competitors

    rayleigh_scale = 2.5 / np.sqrt(total_competitors + 1)
    rows["distance_nearest_competitor_km"] = rng.rayleigh(rayleigh_scale)

    footfall_mean = by_class(urbanicity, 1.5, 0.6, 0.15)
    rows["footfall_generators_count"] = rng.poisson(footfall_mean)

    rows["complementary_retail_ratio"] = beta_mean_conc(rng, 0.45, 20, n)

    # === 3. Accessibility & infrastructure ========================
    transit_mean = 2 + rows["population_density_km2"] / 500
    rows["transit_stops_count"] = neg_binomial_mean_disp(rng, transit_mean, dispersion_factor=2.2, size=n)

    headway_mean = 60 / (1 + rows["transit_stops_count"] / 5)
    headway_mean = np.maximum(headway_mean, 4)
    rows["transit_avg_headway_min"] = rng.gamma(shape=4.0, scale=headway_mean / 4.0)

    parking_mean = by_class(urbanicity, 0.20, 0.50, 0.80)
    parking_latent = beta_mean_conc(rng, parking_mean, 15, n)
    rows["parking_availability"] = pd.cut(
        parking_latent, bins=[-0.01, 0.25, 0.5, 0.75, 1.01],
        labels=["none", "limited", "moderate", "ample"],
    ).astype(str)

    speed_mean = by_class(urbanicity, 22, 35, 48)
    rows["road_avg_commute_speed_kmh"] = np.clip(rng.normal(speed_mean, 6), 8, 70)

    def z(x):
        return (x - np.mean(x)) / np.std(x)

    composite = (
        0.4 * z(rows["population_density_km2"])
        + 0.25 * z(rows["transit_stops_count"])
        + 0.2 * z(rows["footfall_generators_count"])
        + 0.15 * z(rows["competitors_total_count"])
        + rng.normal(0, 0.5, size=n)
    )
    rows["foot_traffic_index"] = 100 * (composite - composite.min()) / (composite.max() - composite.min())

    return pd.DataFrame(rows)


