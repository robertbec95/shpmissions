def attribute_reasoning_doc() -> str:
    lines = [
        "# Synthetic catchment dummy data - attribute scale & distribution reasoning",
        "",
        "100 fabricated locations, generated by `scripts/generate_synthetic_catchment_dummy_data.py`. "
        "**Not real data** - do not merge into `data/location_features/*.json`. Every attribute is "
        "drawn conditional on a per-location `urbanicity` class so the dataset has realistic internal "
        "correlation (e.g. dense catchments also skew younger and better-served by transit), not 25 "
        "independent columns.",
        "",
        "| Category | Attribute | Scale | Distribution | Reasoning |",
        "|---|---|---|---|---|",
    ]
    for category, name, scale, dist, reasoning in ATTRIBUTE_DOCS:
        lines.append(f"| {category} | `{name}` | {scale} | {dist} | {reasoning} |")
    lines.append("")
    lines.append(f"Reproduce with: `PYTHONPATH=src python3 scripts/generate_synthetic_catchment_dummy_data.py`")
    return "\n".join(lines)


